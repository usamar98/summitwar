create or replace function public.get_public_site_stats()
returns table (
  verified_revenue_cents bigint,
  revenue_today_cents bigint,
  revenue_season_cents bigint,
  payment_count bigint,
  average_payment_cents bigint,
  largest_payment_cents bigint,
  paid_startups bigint,
  online_visitors bigint,
  unique_visitors bigint,
  profile_views bigint,
  outbound_clicks bigint,
  total_climbs bigint,
  startups_competing bigint
)
language sql stable security invoker set search_path = '' as $$
  select
    s.verified_revenue_cents,
    coalesce(d.revenue_cents, 0),
    coalesce((select sum(l.current_season_spend_cents) from public.listings l where l.status = 'approved'), 0),
    s.payment_count,
    case when s.payment_count = 0 then 0 else s.verified_revenue_cents / s.payment_count end,
    s.largest_payment_cents,
    s.paid_startups,
    s.online_visitors,
    s.unique_visitors,
    s.profile_views,
    s.outbound_clicks,
    s.payment_count,
    (select count(*) from public.listings l where l.status = 'approved' and l.current_season_spend_cents > 0)
  from public.site_metrics s
  left join public.daily_metrics d on d.metric_date = (now() at time zone 'utc')::date
  where s.singleton = true;
$$;

create or replace function public.consume_rate_limit(p_key text, p_limit integer, p_window_seconds integer)
returns boolean language plpgsql security invoker set search_path = '' as $$
declare
  v_window timestamptz := to_timestamp(floor(extract(epoch from now()) / p_window_seconds) * p_window_seconds);
  v_count integer;
begin
  insert into public.rate_limit_buckets(bucket_key, window_start, request_count)
  values (p_key, v_window, 1)
  on conflict (bucket_key, window_start) do update
    set request_count = public.rate_limit_buckets.request_count + 1
  returning request_count into v_count;
  return v_count <= p_limit;
end;
$$;

create or replace function public.record_profile_view(p_listing_id uuid, p_visitor_hash text)
returns boolean language plpgsql security invoker set search_path = '' as $$
declare
  v_bucket timestamptz := date_trunc('hour', now());
  v_inserted bigint;
begin
  insert into public.profile_view_events(listing_id, visitor_hash, bucket_start)
  values (p_listing_id, p_visitor_hash, v_bucket)
  on conflict do nothing returning id into v_inserted;
  if v_inserted is null then return false; end if;
  update public.listings set lifetime_profile_views = lifetime_profile_views + 1 where id = p_listing_id;
  update public.site_metrics set profile_views = profile_views + 1, updated_at = now() where singleton;
  insert into public.daily_metrics(metric_date, profile_views) values ((now() at time zone 'utc')::date, 1)
  on conflict (metric_date) do update set profile_views = public.daily_metrics.profile_views + 1, updated_at = now();
  return true;
end;
$$;

