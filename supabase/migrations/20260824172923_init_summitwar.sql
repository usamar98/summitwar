-- SummitWar initial schema. All money is integer cents and all season times are UTC.
create extension if not exists pgcrypto;

create type public.listing_status as enum ('pending_payment', 'pending_review', 'approved', 'hidden', 'suspended');
create type public.season_status as enum ('upcoming', 'active', 'closed');
create type public.payment_status as enum ('pending', 'succeeded', 'failed', 'refunded');
create type public.ranking_event_type as enum ('joined', 'climbed', 'summit_taken', 'summit_reclaimed', 'overtaken', 'season_started');

create table public.seasons (
  id uuid primary key default gen_random_uuid(),
  season_number bigint generated by default as identity unique,
  starts_at timestamptz not null,
  ends_at timestamptz not null,
  status public.season_status not null default 'upcoming',
  winner_listing_id uuid,
  runner_up_listing_id uuid,
  winning_spend_cents bigint not null default 0 check (winning_spend_cents >= 0),
  winning_altitude_meters bigint not null default 0 check (winning_altitude_meters >= 0),
  winner_clicks bigint not null default 0 check (winner_clicks >= 0),
  winner_summit_seconds bigint not null default 0 check (winner_summit_seconds >= 0),
  closed_at timestamptz,
  created_at timestamptz not null default now(),
  check (ends_at > starts_at)
);
create unique index seasons_one_active_idx on public.seasons (status) where status = 'active';
create index seasons_dates_idx on public.seasons (starts_at desc, ends_at desc);

create table public.listings (
  id uuid primary key default gen_random_uuid(),
  slug text not null unique check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
  name text not null check (char_length(name) between 1 and 80),
  tagline text not null default '' check (char_length(tagline) <= 160),
  description text not null default '' check (char_length(description) <= 5000),
  website_url text not null,
  normalized_url text not null unique,
  logo_path text,
  logo_url text,
  founder_name text not null default '' check (char_length(founder_name) <= 100),
  founder_x_handle text not null default '' check (char_length(founder_x_handle) <= 32),
  category text not null default 'Other' check (char_length(category) <= 64),
  launch_year smallint not null check (launch_year between 1980 and 2100),
  status public.listing_status not null default 'pending_payment',
  current_season_id uuid references public.seasons(id) on delete set null,
  current_season_spend_cents bigint not null default 0 check (current_season_spend_cents >= 0 and current_season_spend_cents % 100 = 0),
  lifetime_spend_cents bigint not null default 0 check (lifetime_spend_cents >= 0 and lifetime_spend_cents % 100 = 0),
  current_rank integer check (current_rank is null or current_rank > 0),
  first_reached_current_spend_at timestamptz not null default now(),
  summit_wins integer not null default 0 check (summit_wins >= 0),
  total_summit_seconds bigint not null default 0 check (total_summit_seconds >= 0),
  lifetime_profile_views bigint not null default 0 check (lifetime_profile_views >= 0),
  total_outbound_clicks bigint not null default 0 check (total_outbound_clicks >= 0),
  is_demo boolean not null default false,
  approved_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index listings_public_ranking_idx on public.listings (status, current_season_spend_cents desc, first_reached_current_spend_at asc);
create index listings_category_idx on public.listings (status, category);
create index listings_clicks_idx on public.listings (status, total_outbound_clicks desc);
create index listings_lifetime_spend_idx on public.listings (status, lifetime_spend_cents desc);
